param([string]$OutputDirectory)
$ErrorActionPreference='Stop'
if (-not $OutputDirectory) {$OutputDirectory=Join-Path $PSScriptRoot 'dist'}
$dest=[IO.Path]::GetFullPath($OutputDirectory)
$native=Join-Path $PSScriptRoot 'src\native'
$scripts=Join-Path $PSScriptRoot 'src\powershell'
$work=Join-Path $PSScriptRoot 'build'
$compiler=Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path -LiteralPath $compiler)) {throw 'Missing .NET Framework x64 compiler.'}
New-Item -ItemType Directory -Path $dest,$work -Force | Out-Null
& $compiler /nologo /target:winexe /platform:x64 /reference:System.Web.Extensions.dll ('/out:'+(Join-Path $dest 'RouteGuard.exe')) (Join-Path $native 'RouteGuard.cs')
if ($LASTEXITCODE -ne 0) {throw 'RouteGuard build failed'}
# The GUI refuses to run backend files whose SHA-256 differs from what was built next to it.
$hash=@{}
$hash['backend.ps1']=(Get-FileHash -Algorithm SHA256 -LiteralPath (Join-Path $scripts 'backend.ps1')).Hash
$hash['network-core.ps1']=(Get-FileHash -Algorithm SHA256 -LiteralPath (Join-Path $scripts 'network-core.ps1')).Hash
$hash['RouteGuard.exe']=(Get-FileHash -Algorithm SHA256 -LiteralPath (Join-Path $dest 'RouteGuard.exe')).Hash
$buildInfo=Join-Path $work 'BuildInfo.cs'
$lines=@('// Generated by build.ps1. Do not edit.','static class BuildInfo {','    public static readonly string[][] EngineFiles = new string[][] {')
foreach ($name in @('backend.ps1','network-core.ps1','RouteGuard.exe')) {$lines+=('        new string[] {"'+$name+'", "'+$hash[$name]+'"},')}
$lines+=@('    };','}')
[IO.File]::WriteAllLines($buildInfo,$lines,(New-Object Text.UTF8Encoding $false))
& $compiler /nologo /target:winexe /platform:x64 /codepage:65001 /reference:System.Windows.Forms.dll /reference:System.Drawing.dll /reference:System.Web.Extensions.dll ('/win32manifest:'+(Join-Path $native 'app.manifest')) ('/out:'+(Join-Path $dest '双网分流.exe')) (Join-Path $native 'LanSplit.cs') $buildInfo
if ($LASTEXITCODE -ne 0) {throw 'GUI build failed'}
foreach ($name in @('backend.ps1','network-core.ps1','Restore.ps1','Restore.cmd')) {
    Copy-Item -LiteralPath (Join-Path $scripts $name) -Destination (Join-Path $dest $name) -Force
}
Copy-Item -LiteralPath (Join-Path $PSScriptRoot 'docs\使用说明.txt') -Destination (Join-Path $dest '使用说明.txt') -Force
Copy-Item -LiteralPath (Join-Path $PSScriptRoot 'docs\en\user-guide.md') -Destination (Join-Path $dest 'User-Guide.en.md') -Force
foreach ($folder in @('postboot','diagnostics')) {
    $target=Join-Path $dest $folder
    New-Item -ItemType Directory -Path $target -Force | Out-Null
    Get-ChildItem -LiteralPath (Join-Path $PSScriptRoot ('src\'+$folder)) -File | ForEach-Object {Copy-Item -LiteralPath $_.FullName -Destination $target -Force}
}
Get-ChildItem -LiteralPath $dest -File -Recurse | Where-Object Name -ne 'SHA256.csv' | Sort-Object FullName | ForEach-Object {
    [pscustomobject]@{File=$_.FullName.Substring($dest.Length).TrimStart('\'); Hash=(Get-FileHash -Algorithm SHA256 -LiteralPath $_.FullName).Hash}
} | Export-Csv -LiteralPath (Join-Path $dest 'SHA256.csv') -NoTypeInformation -Encoding UTF8
Write-Host ('Build completed: '+$dest+'. No deployment or network changes performed.')
